"""PDF report generation using WeasyPrint.

Produces professional PDF reports from the same HTML template used for
the HTML report, with print-optimized CSS and Devanagari font support.
"""

from __future__ import annotations

import os
from typing import Any

from ishastra.locale import LocaleCode, TemplateContext
from ishastra.report_html import render_html_report


def _resolve_font_paths() -> dict[str, str]:
    """Resolve paths to Devanagari fonts for Nepali language support.

    WeasyPrint uses system fonts. This function finds available Devanagari
    fonts and returns a CSS @font-face block.
    """
    font_dirs = [
        "/usr/share/fonts/truetype/dejavu",
        "/usr/share/fonts/truetype/noto",
        "/usr/share/fonts/truetype/liberation",
        "/usr/share/fonts/opentype/noto",
        "/usr/local/share/fonts",
    ]

    font_files: dict[str, str] = {}

    for font_dir in font_dirs:
        if not os.path.isdir(font_dir):
            continue
        for root, _dirs, files in os.walk(font_dir):
            for f in files:
                fl = f.lower()
                if "noto" in fl and "sans" in fl and "devanagari" in fl and f.endswith((".ttf", ".otf")):
                    font_files["NotoSansDevanagari"] = os.path.join(root, f)
                elif "noto" in fl and "serif" in fl and "devanagari" in fl and f.endswith((".ttf", ".otf")):
                    font_files["NotoSerifDevanagari"] = os.path.join(root, f)
                elif "lohit" in fl and "devanagari" in fl and f.endswith((".ttf", ".otf")):
                    font_files["LohitDevanagari"] = os.path.join(root, f)

    return font_files


def _build_font_face_css() -> str:
    """Build CSS @font-face rules for available Devanagari fonts."""
    fonts = _resolve_font_paths()
    if not fonts:
        return ""

    css_parts = ["/* Devanagari font faces for Nepali language support */"]
    for family, path in fonts.items():
        css_parts.append(f"""
@font-face {{
    font-family: '{family}';
    src: url('file://{path}') format('truetype');
    font-weight: normal;
    font-style: normal;
    font-display: swap;
}}""")
    return "\n".join(css_parts)


def render_pdf_report(
    report: dict[str, Any],
    *,
    output_path: str | None = None,
    locale_code: LocaleCode = "en_US",
    context: TemplateContext | None = None,
) -> bytes:
    """Render an assessment report as PDF using WeasyPrint.

    Args:
        report: Report dictionary (same structure as render_html_report)
        output_path: Optional path to write PDF file
        locale_code: Locale to render in (default: en_US)
        context: Optional template context with localized names

    Returns:
        PDF content as bytes
    """
    try:
        from weasyprint import CSS, HTML
        from weasyprint.text.fonts import FontConfiguration
    except ImportError as exc:
        raise RuntimeError("WeasyPrint is not installed. Install with: pip install weasyprint") from exc

    html_content = render_html_report(report, locale_code=locale_code, context=context)

    font_face_css = _build_font_face_css()
    print_css = _build_print_css()

    if font_face_css or print_css:
        injection = f"<style>\n{font_face_css}\n{print_css}\n</style>"
        html_content = html_content.replace("</head>", f"{injection}\n</head>")

    font_config = FontConfiguration()
    html_doc = HTML(string=html_content)
    css_doc = CSS(string="", font_config=font_config)

    pdf_bytes = html_doc.write_pdf(stylesheets=[css_doc], font_config=font_config)

    if output_path:
        with open(output_path, "wb") as f:
            f.write(pdf_bytes)

    return pdf_bytes


