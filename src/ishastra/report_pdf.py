def generate_pdf_from_job(
    job: dict[str, Any],
    findings: list[dict[str, Any]],
    authorized: dict[str, Any],
    locale_code: LocaleCode = "en_US",
    context: TemplateContext | None = None,
) -> bytes:
    """Generate PDF report from stored job data (for API endpoint).

    This mirrors the logic in assessments.py get_html_report but returns PDF.

    Args:
        job: Job data dictionary
        findings: List of finding dictionaries
        authorized: Authorization data dictionary
        locale_code: Locale to render in (default: en_US)
        context: Optional template context with localized names
    """
    import time
    from collections import Counter

    report = {
        "target": job["target"],
        "job_id": job["id"],
        "state": job["state"],
        "verdict": job["verdict"],
        "coverage": job["coverage"],
        "severity_counts": dict(Counter(f["severity"] for f in findings)),
        "findings": findings,
        "program": authorized["program"],
        "authorized_by": authorized["authorized_by"],
        "authorization_ref": authorized["authorization_ref"],
        "scope_include": authorized["scope_include"],
        "authorization_metadata_available": authorized["available"],
        "policy_id": authorized["policy_id"],
        "policy_version": authorized["policy_version"],
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "integrity": {
            "chain_valid": True,
            "chain_hash": "",
        },
    }
    return render_pdf_report(report, locale_code=locale_code, context=context)
